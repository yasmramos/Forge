package io.github.yasmramos.forge.core.scan;

import io.github.yasmramos.forge.core.graph.TaskScheduler;

import java.time.Instant;
import java.util.List;

/**
 * Renders a local build scan as a self-contained HTML page (AGENT.md section 19).
 *
 * <p>This is the Gradle Enterprise feature offered for free: a timeline of the
 * tasks in a build, their durations, cache hits and misses, and the bottlenecks.
 * No server is involved - the file opens in a browser. The page is intentionally
 * dependency-free (inline CSS, inline SVG-free bars) so it works offline and can
 * be archived as a build artifact.</p>
 */
public final class BuildScanGenerator {

    private BuildScanGenerator() {
    }

    /**
     * Builds the HTML document.
     *
     * @param projectName project name for the header
     * @param timings     per-task timings, in topological order
     * @param totalMillis wall-clock duration of the build
     * @param timestamp   build timestamp; passed in so the output stays
     *                    reproducible (section 17) under a fixed epoch
     */
    public static String generate(String projectName, List<TaskScheduler.TaskTiming> timings,
                                  long totalMillis, Instant timestamp) {
        int executed = 0;
        int cacheHits = 0;
        int failed = 0;
        for (TaskScheduler.TaskTiming t : timings) {
            switch (t.outcome) {
                case EXECUTED:
                    executed++;
                    break;
                case CACHE_HIT:
                    cacheHits++;
                    break;
                default:
                    failed++;
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
        sb.append("<meta charset=\"utf-8\">\n");
        sb.append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        sb.append("<title>Forge build scan - ").append(escape(projectName)).append("</title>\n");
        sb.append("<style>\n").append(css()).append("</style>\n</head>\n<body>\n");

        sb.append("<header>\n");
        sb.append("<h1>Forge build scan</h1>\n");
        sb.append("<p class=\"sub\">").append(escape(projectName)).append(" &middot; ")
            .append(escape(timestamp.toString())).append("</p>\n");
        sb.append("</header>\n");

        sb.append("<section class=\"cards\">\n");
        card(sb, "Total", formatDuration(totalMillis), "");
        card(sb, "Executed", String.valueOf(executed), "executed");
        card(sb, "Cache hits", String.valueOf(cacheHits), "hit");
        card(sb, "Failed", String.valueOf(failed), failed > 0 ? "failed" : "");
        sb.append("</section>\n");

        sb.append("<section>\n<h2>Timeline</h2>\n");
        if (timings.isEmpty()) {
            sb.append("<p class=\"empty\">No tasks were recorded for this build.</p>\n");
        } else {
            sb.append(renderTimeline(timings, totalMillis));
        }
        sb.append("</section>\n");

        sb.append("<section>\n<h2>Tasks</h2>\n");
        sb.append(renderTable(timings));
        sb.append("</section>\n");

        sb.append("<footer>Generated by <strong>forge build --scan</strong> "
            + "(AGENT.md section 19).</footer>\n");
        sb.append("</body>\n</html>\n");
        return sb.toString();
    }

    private static String renderTimeline(List<TaskScheduler.TaskTiming> timings, long totalMillis) {
        long scale = Math.max(totalMillis, 1L);
        StringBuilder sb = new StringBuilder();
        sb.append("<div class=\"timeline\">\n");
        for (TaskScheduler.TaskTiming t : timings) {
            long left = Math.max(0, Math.min(100, (t.startOffsetMillis * 100) / scale));
            long width = Math.max(1, Math.min(100 - left, (t.durationMillis * 100) / scale));
            String color = colorFor(t.outcome);
            sb.append("<div class=\"row\">\n");
            sb.append("<span class=\"label\" title=\"").append(escape(t.name)).append("\">")
                .append(escape(t.name)).append("</span>\n");
            sb.append("<span class=\"track\"><span class=\"bar ").append(color)
                .append("\" style=\"left:").append(left).append("%;width:")
                .append(width).append("%\"></span></span>\n");
            sb.append("<span class=\"dur\">").append(formatDuration(t.durationMillis))
                .append("</span>\n");
            sb.append("</div>\n");
        }
        sb.append("</div>\n");
        return sb.toString();
    }

    private static String renderTable(List<TaskScheduler.TaskTiming> timings) {
        StringBuilder sb = new StringBuilder();
        sb.append("<table>\n<thead><tr>")
            .append("<th>Task</th><th>Type</th><th>Outcome</th><th>Duration</th>")
            .append("<th>Depends on</th></tr></thead>\n<tbody>\n");
        for (TaskScheduler.TaskTiming t : timings) {
            sb.append("<tr>\n");
            sb.append("<td>").append(escape(t.name)).append("</td>\n");
            sb.append("<td>").append(escape(t.type)).append("</td>\n");
            sb.append("<td><span class=\"badge ").append(colorFor(t.outcome)).append("\">")
                .append(escape(t.outcome.name().toLowerCase().replace('_', ' '))).append("</span></td>\n");
            sb.append("<td>").append(formatDuration(t.durationMillis)).append("</td>\n");
            sb.append("<td>").append(t.dependsOn.isEmpty() ? "&mdash;"
                : escape(String.join(", ", t.dependsOn))).append("</td>\n");
            sb.append("</tr>\n");
        }
        sb.append("</tbody>\n</table>\n");
        return sb.toString();
    }

    private static void card(StringBuilder sb, String title, String value, String kind) {
        sb.append("<div class=\"card ").append(kind).append("\">\n")
            .append("<span class=\"value\">").append(escape(value)).append("</span>\n")
            .append("<span class=\"title\">").append(escape(title)).append("</span>\n")
            .append("</div>\n");
    }

    private static String colorFor(TaskScheduler.Outcome outcome) {
        switch (outcome) {
            case CACHE_HIT:
                return "hit";
            case FAILED:
                return "failed";
            default:
                return "executed";
        }
    }

    /** Human-friendly duration; sub-millisecond values are shown as {@code <1 ms}. */
    static String formatDuration(long millis) {
        if (millis < 1) {
            return "<1 ms";
        }
        if (millis < 1000) {
            return millis + " ms";
        }
        return String.format(java.util.Locale.ROOT, "%.2f s", millis / 1000.0);
    }

    private static String escape(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("\"", "&quot;");
    }

    private static String css() {
        return ":root{--bg:#0f1115;--panel:#171a21;--text:#e6e9ef;--muted:#8b93a7;"
            + "--executed:#4c8bf5;--hit:#2fb87a;--failed:#e5534b;--border:#232733}\n"
            + "*{box-sizing:border-box}\n"
            + "body{margin:0;font:14px/1.5 -apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;"
            + "background:var(--bg);color:var(--text)}\n"
            + "header{padding:24px 32px;border-bottom:1px solid var(--border)}\n"
            + "h1{margin:0;font-size:22px}h2{font-size:16px;margin:0 0 12px}\n"
            + ".sub{color:var(--muted);margin:4px 0 0}\n"
            + "section{padding:20px 32px}\n"
            + ".cards{display:flex;gap:16px;flex-wrap:wrap}\n"
            + ".card{background:var(--panel);border:1px solid var(--border);border-radius:10px;"
            + "padding:14px 18px;min-width:120px;display:flex;flex-direction:column}\n"
            + ".card .value{font-size:24px;font-weight:600}\n"
            + ".card .title{color:var(--muted);font-size:12px;text-transform:uppercase;"
            + "letter-spacing:.04em}\n"
            + ".card.hit .value{color:var(--hit)}.card.failed .value{color:var(--failed)}\n"
            + ".timeline{display:flex;flex-direction:column;gap:6px}\n"
            + ".row{display:grid;grid-template-columns:140px 1fr 72px;align-items:center;gap:12px}\n"
            + ".row .label{color:var(--muted);white-space:nowrap;overflow:hidden;text-overflow:ellipsis}\n"
            + ".track{position:relative;height:14px;background:var(--panel);border-radius:7px;"
            + "overflow:hidden}\n"
            + ".bar{position:absolute;top:0;height:100%;border-radius:7px;min-width:2px}\n"
            + ".bar.executed,.badge.executed{background:var(--executed)}\n"
            + ".bar.hit,.badge.hit{background:var(--hit)}\n"
            + ".bar.failed,.badge.failed{background:var(--failed)}\n"
            + ".row .dur{color:var(--muted);text-align:right}\n"
            + "table{width:100%;border-collapse:collapse;background:var(--panel);border-radius:10px;"
            + "overflow:hidden}\n"
            + "th,td{text-align:left;padding:10px 14px;border-bottom:1px solid var(--border)}\n"
            + "th{color:var(--muted);font-weight:500;text-transform:uppercase;font-size:11px;"
            + "letter-spacing:.04em}\n"
            + "tr:last-child td{border-bottom:none}\n"
            + ".badge{padding:2px 8px;border-radius:999px;font-size:11px;color:#fff}\n"
            + ".empty{color:var(--muted)}\n"
            + "footer{padding:20px 32px;color:var(--muted);border-top:1px solid var(--border)}\n";
    }
}
