package io.github.yasmramos.forge.core.importer;

import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * Renders a {@link BuildModel} as a {@code forge.toml} (AGENT.md sections 14 and
 * 15).
 *
 * <p>The output is intentionally close to what {@code forge init} writes and to
 * the example projects, so an imported file looks like a hand-written one:
 * stable section order, aligned keys, no trailing noise. Values that would
 * interpolate as {@code ${...}} keep working because the same property
 * definitions are emitted under {@code [project.properties]}.</p>
 */
public final class ForgeTomlWriter {

    private ForgeTomlWriter() {
    }

    /** Renders the model as a complete forge.toml document. */
    public static String write(BuildModel model) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by 'forge import' (AGENT.md section 14).\n");
        sb.append("# Review the TODO comments below: an import covers the common case,\n");
        sb.append("# not every build nuance.\n");
        sb.append('\n');
        sb.append("forge = \"0.1\"\n");
        sb.append('\n');

        sb.append("[project]\n");
        sb.append("name    = \"").append(escape(model.getName())).append("\"\n");
        sb.append("version = \"").append(escape(model.getVersion())).append("\"\n");
        if (notBlank(model.getGroup())) {
            sb.append("group   = \"").append(escape(model.getGroup())).append("\"\n");
        }
        if (notBlank(model.getDescription())) {
            sb.append("description = \"").append(escape(model.getDescription())).append("\"\n");
        }
        if (notBlank(model.getPackaging()) && !"jar".equals(model.getPackaging())) {
            sb.append("packaging = \"").append(escape(model.getPackaging())).append("\"\n");
        }

        if (!model.getProperties().isEmpty()) {
            sb.append('\n');
            sb.append("[project.properties]\n");
            for (Map.Entry<String, String> e : model.getProperties().entrySet()) {
                sb.append('"').append(escape(e.getKey())).append("\" = \"")
                    .append(escape(e.getValue())).append("\"\n");
            }
        }

        sb.append('\n');
        sb.append("[repositories]\n");
        if (model.getRepositories().isEmpty()) {
            sb.append("central = \"https://repo1.maven.org/maven2\"\n");
        } else {
            for (Map.Entry<String, String> e : model.getRepositories().entrySet()) {
                // Quote the key: an unquoted key containing a dot (e.g. a
                // hostname) parses as a nested table in TOML and would silently
                // drop the repository.
                sb.append('"').append(escape(e.getKey())).append("\" = \"")
                    .append(escape(e.getValue())).append("\"\n");
            }
        }

        if (notBlank(model.getLanguage())) {
            sb.append('\n');
            sb.append("[toolchain]\n");
            sb.append("language = \"").append(escape(model.getLanguage())).append("\"\n");
        }

        if (!model.getMainJavaSources().isEmpty() || !model.getTestJavaSources().isEmpty()) {
            sb.append('\n');
            sb.append("[source.main]\n");
            sb.append("java = ").append(renderList(model.getMainJavaSources())).append("\n");
            if (!model.getTestJavaSources().isEmpty()) {
                sb.append('\n');
                sb.append("[source.test]\n");
                sb.append("java = ").append(renderList(model.getTestJavaSources())).append("\n");
            }
        }

        renderDependencies(sb, model);

        sb.append('\n');
        sb.append("[build]\n");
        sb.append("incremental   = true\n");
        sb.append("cache_enabled = true\n");

        if (notBlank(model.getMainClass())) {
            sb.append('\n');
            sb.append("[exec]\n");
            sb.append("main = \"").append(escape(model.getMainClass())).append("\"\n");
        }

        if (!model.getTodos().isEmpty()) {
            sb.append('\n');
            for (String todo : model.getTodos()) {
                sb.append("# TODO: ").append(todo).append('\n');
            }
        }
        return sb.toString();
    }

    private static void renderDependencies(StringBuilder sb, BuildModel model) {
        Map<String, Set<BuildModel.Dependency>> byScope = new TreeMap<>();
        for (String scope : new String[] {"compile", "runtime", "test", "provided"}) {
            byScope.put(scope, new LinkedHashSet<>());
        }
        for (BuildModel.Dependency dep : model.getDependencies()) {
            byScope.computeIfAbsent(dep.scope, k -> new LinkedHashSet<>()).add(dep);
        }

        // Always emit [dependencies.compile] and [dependencies.test] so the file
        // matches the shape forge init produces and reads naturally.
        for (String scope : new String[] {"compile", "runtime", "test", "provided"}) {
            Set<BuildModel.Dependency> deps = byScope.getOrDefault(scope, new LinkedHashSet<>());
            if (deps.isEmpty() && !"compile".equals(scope) && !"test".equals(scope)) {
                continue;
            }
            sb.append('\n');
            sb.append("[dependencies.").append(scope).append("]\n");
            for (BuildModel.Dependency dep : deps) {
                if (dep.version == null) {
                    // No declared version: writing an assignment would produce a
                    // forge.toml that cannot resolve. Comment it instead; the
                    // matching TODO explains the fix.
                    sb.append("# \"").append(escape(dep.coordinate))
                        .append("\" = \"<version>\"  # TODO: no version was declared\n");
                } else {
                    sb.append('"').append(escape(dep.coordinate)).append("\" = \"")
                        .append(escape(dep.version)).append("\"\n");
                }
            }
        }
    }

    private static String renderList(List<String> values) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) {
                sb.append(", ");
            }
            sb.append('"').append(escape(values.get(i))).append('"');
        }
        return sb.append(']').toString();
    }

    private static String escape(String value) {
        return value == null ? "" : value.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    private static boolean notBlank(String value) {
        return value != null && !value.trim().isEmpty();
    }
}
