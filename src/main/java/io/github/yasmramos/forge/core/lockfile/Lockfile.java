package io.github.yasmramos.forge.core.lockfile;

import io.github.yasmramos.forge.cli.error.ErrorCode;
import io.github.yasmramos.forge.cli.error.ForgeException;

import java.io.ByteArrayInputStream;
import java.io.File;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.electronwill.nightconfig.core.Config;
import com.electronwill.nightconfig.toml.TomlParser;

/**
 * forge.lock: fully resolved dependency set with exact versions and checksums
 * (AGENT.md decision 7, format specified in section 7bis). Committed to
 * version control, updated only by an explicit command (forge update /
 * forge lock refresh), never during a build.
 *
 * <p>Format rules implemented here:
 * <ul>
 *   <li>{@code lockfile_version} — schema of this file, decoupled from the
 *       {@code forge} key of forge.toml. Newer schemas fail with
 *       FORGE-LCK-0002.</li>
 *   <li>Canonical serialization — entries sorted by coordinate then version,
 *       keys written in fixed order. Diffs must show only real changes.</li>
 *   <li>Self-integrity — the final line is {@code content_hash = "sha256:..."}
 *       computed over everything above it; mismatch fails with
 *       FORGE-LCK-0001.</li>
 *   <li>Staleness — {@code config_hash} ties the lock to one exact resolved
 *       configuration; mismatch fails with FORGE-LCK-0003.</li>
 * </ul>
 */
public class Lockfile {

    public static final String FILE_NAME = "forge.lock";
    public static final String LOCKFILE_VERSION = "0.1";

    private static final String CONTENT_HASH_KEY = "content_hash";

    public static class LockedDependency {
        public final String coordinate; // group:artifact
        public final String version;    // exact resolved version
        public final String sha256;     // content checksum (mandatory)
        public final String repository; // source repo URL

        public LockedDependency(String coordinate, String version, String sha256, String repository) {
            this.coordinate = coordinate;
            this.version = version;
            this.sha256 = sha256;
            this.repository = repository;
        }
    }

    private final String configHash;
    private final Map<String, LockedDependency> dependencies;

    public Lockfile(String configHash, Map<String, LockedDependency> dependencies) {
        this.configHash = configHash;
        // Deterministic ordering by coordinate for diff-friendly output.
        this.dependencies = new LinkedHashMap<>();
        new ArrayList<>(dependencies.keySet()).stream().sorted()
            .forEach(k -> this.dependencies.put(k, dependencies.get(k)));
    }

    public String getConfigHash() { return configHash; }
    public Map<String, LockedDependency> getDependencies() { return dependencies; }

    /** SHA-256 over the raw forge.toml bytes; ties the lock to one exact config. */
    public static String hashOf(File forgeToml) throws Exception {
        return sha256Hex(Files.readAllBytes(forgeToml.toPath()));
    }

    private static String sha256Hex(byte[] data) throws Exception {
        MessageDigest digest = MessageDigest.getInstance("SHA-256");
        StringBuilder sb = new StringBuilder();
        for (byte b : digest.digest(data)) {
            sb.append(String.format("%02x", b));
        }
        return sb.toString();
    }

    /**
     * Canonical body serialization: header keys first in fixed order, then
     * one [[dependency]] table per entry sorted by coordinate then version,
     * each with keys in fixed order. Two Lockfiles with equal content always
     * produce byte-identical bodies (tested invariant, section 7bis).
     */
    private String canonicalBody() {
        StringBuilder sb = new StringBuilder();
        sb.append("# forge.lock - generated by Forge. Do not edit manually.\n");
        sb.append("# Merge policy: on conflict, delete or take either side and run 'forge lock refresh'.\n");
        sb.append("lockfile_version = \"").append(LOCKFILE_VERSION).append("\"\n");
        sb.append("config_hash      = \"sha256:").append(configHash).append("\"\n");
        for (LockedDependency d : dependencies.values()) {
            sb.append("\n[[dependency]]\n");
            sb.append("coordinate = \"").append(d.coordinate).append("\"\n");
            sb.append("version    = \"").append(d.version).append("\"\n");
            sb.append("repository = \"").append(d.repository).append("\"\n");
            sb.append("sha256     = \"sha256:").append(d.sha256).append("\"\n");
        }
        return sb.toString();
    }

    /** Writes body plus trailing self-integrity hash (FORGE-LCK-0001 anchor). */
    public void write(File projectRoot) throws Exception {
        String body = canonicalBody();
        String hash = sha256Hex(body.getBytes(StandardCharsets.UTF_8));
        File out = new File(projectRoot, FILE_NAME);
        try (OutputStream os = Files.newOutputStream(out.toPath())) {
            os.write(body.getBytes(StandardCharsets.UTF_8));
            os.write(("content_hash = \"sha256:" + hash + "\"\n")
                .getBytes(StandardCharsets.UTF_8));
        }
    }

    public static Lockfile read(File projectRoot) throws Exception {
        File f = new File(projectRoot, FILE_NAME);
        if (!f.isFile()) {
            throw new ForgeException(ErrorCode.LCK_0004, FILE_NAME + " not found in "
                + projectRoot.getAbsolutePath());
        }
        List<String> lines = Files.readAllLines(f.toPath(), StandardCharsets.UTF_8);

        // Split off the trailing self-integrity line and verify it (LCK-0001).
        int contentIdx = -1;
        for (int i = lines.size() - 1; i >= 0; i--) {
            if (lines.get(i).trim().startsWith(CONTENT_HASH_KEY)) {
                contentIdx = i;
                break;
            }
        }
        if (contentIdx < 0) {
            throw new ForgeException(ErrorCode.LCK_0001,
                FILE_NAME + " has no content_hash line");
        }
        StringBuilder bodySb = new StringBuilder();
        for (int i = 0; i < contentIdx; i++) {
            bodySb.append(lines.get(i)).append('\n');
        }
        String declared = extractQuoted(lines.get(contentIdx));
        String actual = sha256Hex(bodySb.toString().getBytes(StandardCharsets.UTF_8));
        if (declared == null || !declared.equals("sha256:" + actual)) {
            throw new ForgeException(ErrorCode.LCK_0001,
                FILE_NAME + " body does not match its content_hash");
        }

        // Parse the verified body with NightConfig.
        Config cfg;
        try (InputStream is = new ByteArrayInputStream(
                bodySb.toString().getBytes(StandardCharsets.UTF_8))) {
            cfg = new TomlParser().parse(is);
        }

        String schema = cfg.get("lockfile_version");
        if (schema == null) {
            throw new ForgeException(ErrorCode.LCK_0001, FILE_NAME + " missing lockfile_version");
        }
        if (compareSchema(schema, LOCKFILE_VERSION) > 0) {
            throw new ForgeException(ErrorCode.LCK_0002,
                FILE_NAME + " declares schema " + schema + ", this Forge supports " + LOCKFILE_VERSION);
        }

        String hash = stripAlgo(cfg.get("config_hash"));
        Map<String, LockedDependency> deps = new LinkedHashMap<>();
        for (Object o : cfg.getOrElse("dependency", new ArrayList<>())) {
            Config c = (Config) o;
            LockedDependency d = new LockedDependency(
                (String) c.get("coordinate"), (String) c.get("version"),
                stripAlgo((String) c.get("sha256")), (String) c.get("repository"));
            deps.put(d.coordinate, d);
        }
        return new Lockfile(hash, deps);
    }

    /** Fails the build when the lock was produced from a different configuration. */
    public void verifyAgainst(File forgeToml) throws Exception {
        String current = hashOf(forgeToml);
        if (!current.equals(configHash)) {
            throw new ForgeException(ErrorCode.LCK_0003,
                "config_hash mismatch: lock was built from a different forge.toml");
        }
    }

    // --- small helpers ---

    private static String extractQuoted(String line) {
        int a = line.indexOf('"');
        int b = line.lastIndexOf('"');
        return (a < 0 || b <= a) ? null : line.substring(a + 1, b);
    }

    private static String stripAlgo(String v) {
        if (v == null) {
            return null;
        }
        int i = v.indexOf(':');
        return i >= 0 ? v.substring(i + 1) : v;
    }

    /** Compares dotted numeric schema versions; returns -1, 0 or 1. */
    private static int compareSchema(String a, String b) {
        String[] pa = a.split("\\.");
        String[] pb = b.split("\\.");
        int n = Math.max(pa.length, pb.length);
        for (int i = 0; i < n; i++) {
            int va = i < pa.length ? Integer.parseInt(pa[i].trim()) : 0;
            int vb = i < pb.length ? Integer.parseInt(pb[i].trim()) : 0;
            if (va != vb) {
                return Integer.compare(va, vb);
            }
        }
        return 0;
    }
}
