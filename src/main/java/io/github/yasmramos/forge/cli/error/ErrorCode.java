package io.github.yasmramos.forge.cli.error;

import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

import com.electronwill.nightconfig.core.Config;
import com.electronwill.nightconfig.toml.TomlParser;

/**
 * Registry of stable error codes (AGENT.md section 10bis).
 *
 * <p>Codes follow the pattern {@code FORGE-<PREFIX>-<NNNN>} with domain
 * prefixes: CFG (config), DEP (resolution), LCK (lockfile), TSK (graph and
 * tasks), PLG (plugins), NET (network), CCH (cache), VRT (variants),
 * RUN (process execution), RPR (reproducibility), INT (internal bugs).
 *
 * <p>A shipped code is public API: it is never reused or renumbered. The
 * catalog lives in {@code docs/errors.toml} inside the jar resources so tests
 * can validate that no error is thrown with an unregistered code and that
 * every registered entry carries what/why/how/docs fields.
 */
public final class ErrorCode {

    /** One catalog entry: a stable code plus its documentation fields. */
    public static final class Entry {
        private final String code;
        private final String what;
        private final String why;
        private final String how;
        private final String docsUrl;

        Entry(String code, String what, String why, String how, String docsUrl) {
            this.code = code;
            this.what = what;
            this.why = why;
            this.how = how;
            this.docsUrl = docsUrl;
        }

        public String getCode()    { return code; }
        public String getWhat()    { return what; }
        public String getWhy()     { return why; }
        public String getHow()     { return how; }
        public String getDocsUrl() { return docsUrl; }
    }

    // --- Lockfile (LCK) ---
    public static final Entry LCK_0001 = register("FORGE-LCK-0001",
        "The content hash at the end of forge.lock does not match the file body.",
        "The lockfile was edited by hand, truncated, or corrupted during transfer.",
        "Delete forge.lock and run 'forge lock refresh' to regenerate it deterministically.",
        "https://forge.dev/e/LCK-0001");
    public static final Entry LCK_0002 = register("FORGE-LCK-0002",
        "forge.lock uses a newer schema version than this Forge installation understands.",
        "The lockfile was generated by a future Forge release.",
        "Upgrade Forge, or regenerate the lock with the Forge version pinned for this project.",
        "https://forge.dev/e/LCK-0002");
    public static final Entry LCK_0003 = register("FORGE-LCK-0003",
        "forge.lock is stale: its config_hash does not match the current resolved configuration.",
        "forge.toml (or the selected variant) changed after the last lock refresh.",
        "Run 'forge lock refresh' and commit the updated forge.lock.",
        "https://forge.dev/e/LCK-0003");
    public static final Entry LCK_0004 = register("FORGE-LCK-0004",
        "forge.lock is missing from the project root.",
        "A build requires a committed lockfile so dependency sets are pinned consciously.",
        "Run 'forge update' to generate forge.lock, then commit it.",
        "https://forge.dev/e/LCK-0004");

    // --- Task graph (TSK) ---
    public static final Entry TSK_0001 = register("FORGE-TSK-0001",
        "The task graph contains a dependency cycle.",
        "Cycles make any execution order impossible, so nothing can run safely.",
        "Remove or invert one edge in the reported cycle, then rebuild.",
        "https://forge.dev/e/TSK-0001");
    public static final Entry TSK_0002 = register("FORGE-TSK-0002",
        "A task declares a dependency on a task name that does not exist.",
        "Typos or deleted tasks leave dangling references in the graph.",
        "Fix the dependsOn/softDependsOn reference to point at a declared task.",
        "https://forge.dev/e/TSK-0002");
    public static final Entry TSK_0003 = register("FORGE-TSK-0003",
        "Two tasks share the same name in the graph.",
        "Task names are unique identifiers used for dependencies and cache keys.",
        "Rename one of the conflicting tasks.",
        "https://forge.dev/e/TSK-0003");

    // --- Cache (CCH) ---
    // --- RSL: dependency resolution domain (AGENT.md section 2bis) ---

    public static final Entry RSL_0001 = register("FORGE-RSL-0001",
        "Version conflict detected while resolving dependencies.",
        "Two or more paths request different versions of the same artifact and no exact alignment exists; Forge fails by default instead of silently picking one.",
        "Pin a version with [resolutions] in forge.toml, import a BOM that aligns the versions, or run 'forge resolve --explain' to see who requests what. Then run 'forge lock refresh'.",
        "https://forge.dev/e/RSL-0001");

    public static final Entry CCH_0001 = register("FORGE-CCH-0001",
        "A cached output archive failed integrity verification while being restored.",
        "The local cache entry was corrupted on disk.",
        "Run 'forge clean-cache' (or delete .forge/cache) to discard the damaged entry; the next build repopulates it.",
        "https://forge.dev/e/CCH-0001");

    // --- Reproducibility (RPR) ---
    public static final Entry RPR_0001 = register("FORGE-RPR-0001",
        "A plugin produced outputs that differ between two identical builds.",
        "Bit-for-bit reproducibility is guaranteed for core tasks only; plugins are best-effort (AGENT.md section 17).",
        "Report the behavior to the plugin author, or enable strict mode with [build] reproducible_strict = true to fail instead of warn.",
        "https://forge.dev/e/RPR-0001");

    // --- Internal (INT) ---
    public static final Entry INT_0001 = register("FORGE-INT-0001",
        "An unexpected internal error occurred.",
        "This indicates a bug in Forge itself, not in your project.",
        "Re-run with --debug to capture details and file an issue including the structured error block.",
        "https://forge.dev/e/INT-0001");

    private static final Map<String, Entry> CATALOG;

    private static synchronized Entry register(String code, String what, String why,
                                               String how, String docsUrl) {
        // Registration order is irrelevant; the map is rebuilt sorted below.
        if (TEMP == null) {
            TEMP = new LinkedHashMap<>();
        }
        Entry e = new Entry(code, what, why, how, docsUrl);
        if (TEMP.put(code, e) != null) {
            throw new IllegalStateException("Duplicate error code: " + code);
        }
        return e;
    }

    private static Map<String, Entry> TEMP;

    static {
        Map<String, Entry> sorted = new LinkedHashMap<>();
        TEMP.keySet().stream().sorted().forEach(k -> sorted.put(k, TEMP.get(k)));
        CATALOG = Collections.unmodifiableMap(sorted);
    }

    private ErrorCode() {
    }

    /** All registered codes, sorted by code. Keys include the FORGE- prefix. */
    public static Map<String, Entry> catalog() {
        return CATALOG;
    }

    public static Entry lookup(String code) {
        return CATALOG.get(code);
    }

    /** True when the string is a well-formed, registered code. */
    public static boolean isRegistered(String code) {
        return CATALOG.containsKey(code);
    }

    /**
     * Loads the machine-readable catalog shipped as a classpath resource
     * (docs/errors.toml). Used by CI tests to cross-check the Java registry
     * against the documented catalog so neither can drift.
     */
    public static Map<String, Config> loadCatalogResource() throws IOException {
        try (InputStream is = ErrorCode.class.getResourceAsStream("/docs/errors.toml")) {
            if (is == null) {
                throw new IOException("Bundled catalog /docs/errors.toml not found on classpath");
            }
            Config root = new TomlParser().parse(is);
            Map<String, Config> out = new LinkedHashMap<>();
            for (Map.Entry<String, Object> e : root.valueMap().entrySet()) {
                if (e.getValue() instanceof Config) {
                    out.put(e.getKey(), (Config) e.getValue());
                }
            }
            return out;
        }
    }

    /** Convenience: absolute path helper kept for callers that resolve files. */
    public static File resolveProjectFile(File root, String name) {
        return new File(root, name);
    }

    /** Reads bytes of any file; small shared helper used by error-context dumps. */
    public static byte[] readBytes(File f) throws IOException {
        return Files.readAllBytes(f.toPath());
    }
}
