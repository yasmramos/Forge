    private static final Map<String, Entry> CATALOG;

    private static synchronized Entry register(String code, String what, String why,
                                               String how, String docsUrl) {
        // Registration order is irrelevant; the map is rebuilt sorted below.
        if (TEMP == null) {
            TEMP = new LinkedHashMap<>();
        }
        Entry e = new Entry(code, what, why, how, docsUrl);
        if (TEMP.put(code, e) != null) {
            throw new IllegalStateException("Duplicate error code: " + code);
        }
        return e;
    }

    private static Map<String, Entry> TEMP;

    static {
        Map<String, Entry> sorted = new LinkedHashMap<>();
        TEMP.keySet().stream().sorted().forEach(k -> sorted.put(k, TEMP.get(k)));
        CATALOG = Collections.unmodifiableMap(sorted);
    }

    private ErrorCode() {
    }

    /** All registered codes, sorted by code. Keys include the FORGE- prefix. */
    public static Map<String, Entry> catalog() {
        return CATALOG;
    }

    public static Entry lookup(String code) {
        return CATALOG.get(code);
    }

    /** True when the string is a well-formed, registered code. */
    public static boolean isRegistered(String code) {
        return CATALOG.containsKey(code);
    }

    /**
     * Loads the machine-readable catalog shipped as a classpath resource
     * (docs/errors.toml). Used by CI tests to cross-check the Java registry
     * against the documented catalog so neither can drift.
     */
    public static Map<String, Config> loadCatalogResource() throws IOException {
        try (InputStream is = ErrorCode.class.getResourceAsStream("/docs/errors.toml")) {
            if (is == null) {
                throw new IOException("Bundled catalog /docs/errors.toml not found on classpath");
            }
            Config root = new TomlParser().parse(is);
            Map<String, Config> out = new LinkedHashMap<>();
            for (Map.Entry<String, Object> e : root.valueMap().entrySet()) {
                if (e.getValue() instanceof Config) {
                    out.put(e.getKey(), (Config) e.getValue());
                }
            }
            return out;
        }
    }

    /** Convenience: absolute path helper kept for callers that resolve files. */
    public static File resolveProjectFile(File root, String name) {
        return new File(root, name);
    }

    /** Reads bytes of any file; small shared helper used by error-context dumps. */
    public static byte[] readBytes(File f) throws IOException {
        return Files.readAllBytes(f.toPath());
    }
